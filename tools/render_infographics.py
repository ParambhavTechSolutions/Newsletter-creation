"""Render branded infographic PNGs from content.json using Playwright (headless Chromium).

Usage: .venv/bin/python tools/render_infographics.py .tmp/<slug>/content.json

Each item in content["infographics"] needs: id, type (stats|timeline|comparison|quote|chart|ai),
theme (dark|light), title, alt, source, plus type-specific data (see templates/infographics/*.j2).
"ai" items need "prompt" (scene only, no text/numbers) and optional "aspect" (default 16:9); the
illustration is generated by generate_ai_infographic.py (Cloudflare Workers AI, free, cached) and framed in the brand card.
Output: .tmp/<slug>/img/<id>.png  (1200px wide = 600 CSS px @2x)
"""
import argparse
from pathlib import Path

from jinja2 import ChainableUndefined, Environment, FileSystemLoader
from playwright.sync_api import sync_playwright

from common import ROOT, TEMPLATES, fail, load_brand, load_json

TYPES = {"stats", "timeline", "comparison", "quote", "chart", "ai"}
REQUIRED = {
    "stats": ["stats"], "timeline": ["events"], "comparison": ["left", "right"],
    "quote": ["quote", "speaker"], "chart": ["chart"], "ai": ["prompt"],
}


def validate(g):
    missing = [k for k in ("id", "type", "title", "alt") if not g.get(k)]
    if g.get("type") not in TYPES:
        return f"type must be one of {sorted(TYPES)}"
    missing += [k for k in REQUIRED[g["type"]] if not g.get(k)]
    if missing:
        return f"missing fields: {missing}"
    if g.get("theme", "light") not in ("dark", "light"):
        return "theme must be dark or light"
    return None


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("content_json")
    ap.add_argument("--only", help="render a single infographic id")
    args = ap.parse_args()

    content_path = Path(args.content_json).resolve()
    content = load_json(content_path)
    brand = load_brand()
    out_dir = content_path.parent / "img"
    html_dir = content_path.parent / "infographics_html"
    out_dir.mkdir(exist_ok=True)
    html_dir.mkdir(exist_ok=True)

    env = Environment(loader=FileSystemLoader(TEMPLATES / "infographics"), autoescape=True,
                      undefined=ChainableUndefined)
    common_ctx = {
        "c": brand["colors"],
        "ramp": brand["chart_ramp"],
        "fonts": {k: (ROOT / v).as_uri() for k, v in brand["fonts"]["files"].items()},
        "symbol": (ROOT / brand["logo"]["email_symbol"]).as_uri(),
        "chartjs": (TEMPLATES / "vendor" / "chart.umd.min.js").as_uri(),
    }

    items = content.get("infographics", [])
    if args.only:
        items = [g for g in items if g.get("id") == args.only]
    if not items:
        fail("No infographics to render in content.json")

    errors = 0
    with sync_playwright() as p:
        browser = p.chromium.launch()
        page = browser.new_page(viewport={"width": 600, "height": 800}, device_scale_factor=2)
        for g in items:
            err = validate(g)
            if err:
                print(f"  SKIP {g.get('id', '?')}: {err}")
                errors += 1
                continue
            g.setdefault("theme", "light")
            for k in ("eyebrow", "subtitle", "source"):
                g.setdefault(k, "")
            if g["type"] == "chart":
                g["chart"].setdefault("height", 300)
            if g["type"] == "ai":
                from generate_ai_infographic import generate
                raw = generate(g["prompt"], out_dir / f"{g['id']}_raw.png", g.get("aspect", "16:9"))
                g["image_uri"] = raw.resolve().as_uri()
            try:
                html = env.get_template(f"{g['type']}.html.j2").render(g=g, **common_ctx)
            except Exception as e:  # template errors should name the infographic
                print(f"  FAIL {g['id']}: template error: {e}")
                errors += 1
                continue
            html_path = html_dir / f"{g['id']}.html"
            html_path.write_text(html)
            page.goto(html_path.as_uri())
            try:
                page.wait_for_function("window.__ready === true", timeout=15000)
            except Exception:
                print(f"  FAIL {g['id']}: page never signalled ready (JS error?)")
                errors += 1
                continue
            out = out_dir / f"{g['id']}.png"
            page.locator("#card").screenshot(path=str(out))
            print(f"  OK   {out.relative_to(ROOT)}")
        browser.close()

    if errors:
        fail(f"{errors} infographic(s) failed")
    print(f"OK  rendered {len(items)} infographic(s)")


if __name__ == "__main__":
    main()
